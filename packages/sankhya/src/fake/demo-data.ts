/** Wrong-on-purpose check digits: the first digit is always different from the correct one. */
function weightedDigit(digits: readonly number[], weights: readonly number[]): number {
  const sum = digits.reduce((acc, digit, index) => acc + digit * (weights[index] ?? 0), 0);
  const remainder = sum % 11;
  return remainder < 2 ? 0 : 11 - remainder;
}

function fakeCnpj(sequence: number): string {
  const base = `9999${String(sequence).padStart(4, '0')}0001`.split('').map(Number);
  const correct = weightedDigit(base, [5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2]);
  const first = (correct + 1) % 10;
  const second = weightedDigit([...base, first], [6, 5, 4, 3, 2, 9, 8, 7, 6, 5, 4, 3, 2]);
  return `${base.join('')}${first}${second}`;
}

function fakeCpf(sequence: number): string {
  const base = `999${String(sequence).padStart(6, '0')}`.split('').map(Number);
  const correct = weightedDigit(base, [10, 9, 8, 7, 6, 5, 4, 3, 2]);
  const first = (correct + 1) % 10;
  const second = weightedDigit([...base, first], [11, 10, 9, 8, 7, 6, 5, 4, 3, 2]);
  return `${base.join('')}${first}${second}`;
}

function buildCustomers(rng: Prng, sellers: readonly Seller[]): Customer[] {
  const activeSellers = sellers.filter((s) => s.active && s.code > 102).map((s) => s.code);
  const inactiveSeller = sellers.find((s) => !s.active)?.code ?? null;
  const usedNames = new Set<string>();
  const customers: Customer[] = [];
  let code = CUSTOMER_FIRST_CODE;

  for (let index = 0; index < CUSTOMER_COUNT; index += 1) {
    code += rng.int(1, 4);
    const isCompany = rng.chance(0.78);

    let name: string;
    let tradeName: string;
    for (let attempt = 0; ; attempt += 1) {
      if (isCompany) {
        const root = rng.pick(COMPANY_ROOTS);
        const segment = rng.pick(COMPANY_SEGMENTS);
        tradeName = attempt < 30 ? `${root} ${segment}` : `${root} ${segment} ${index + 1}`;
        name = `${tradeName} ${rng.pick(COMPANY_SUFFIXES)}`;
      } else {
        tradeName = `${rng.pick(GIVEN_NAMES)} ${rng.pick(SURNAMES)}`;
        if (attempt >= 30) tradeName = `${tradeName} ${index + 1}`;
        name = tradeName;
      }
      if (!usedNames.has(name)) break;
    }
    usedNames.add(name);

    const active = !rng.chance(0.08);
    const blocked = active && rng.chance(0.04);

    let sellerCode: number | null;
    const sellerRoll = rng.next();
    if (sellerRoll < 0.06) sellerCode = null;
    else if (sellerRoll < 0.11 && inactiveSeller !== null) sellerCode = inactiveSeller;
    else sellerCode = rng.pick(activeSellers);

    // The fallback table is deliberately never a customer's own table.
    const priceTableCode = rng.weighted<number | null>([
      [DEMO_MAIN_TABLE_CODE, 80],
      [DEMO_DERIVED_TABLE_CODE, 12],
      [null, 8],
    ]);

    const creditLimit = rng.chance(0.12)
      ? null
      : fixedToDecimal(
          Math.max(0, rng.pick(CREDIT_STEPS) + rng.int(-4, 4) * 250 * (rng.chance(0.5) ? 1 : 0)) * 100 +
            (rng.chance(0.2) ? 50 : 0),
          2,
        );

    const document = rng.chance(0.01) ? null : isCompany ? fakeCnpj(index + 1) : fakeCpf(index + 1);

    customers.push({
      code,
      name,
      tradeName,
      document,
      active,
      blocked,
      sellerCode,
      priceTableCode,
      creditLimit,
    });
  }
  return customers;
}

