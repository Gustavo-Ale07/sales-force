interface ProductBuild {
  readonly product: Product;
  /** Base price in 10^-4 currency units. */
  readonly basePrice: number;
}

function buildProducts(rng: Prng): { groups: ProductGroup[]; products: ProductBuild[] } {
  const groups: ProductGroup[] = GROUP_SPECS.map((spec, index) => ({ code: GROUP_FIRST_CODE + index, name: spec.name }));
  const usedDescriptions = new Set<string>();
  const products: ProductBuild[] = [];
  let code = PRODUCT_FIRST_CODE;

  for (let index = 0; index < PRODUCT_COUNT; index += 1) {
    code += rng.int(1, 3);
    const groupIndex = rng.int(0, GROUP_SPECS.length - 1);
    const spec = GROUP_SPECS[groupIndex];
    if (spec === undefined) throw new RangeError('group spec missing');

    let description: string;
    for (let attempt = 0; ; attempt += 1) {
      description = `${rng.pick(spec.items)} ${rng.pick(spec.specs)}`;
      if (attempt >= 20) description = `${description} #${index + 1}`;
      if (!usedDescriptions.has(description)) break;
    }
    usedDescriptions.add(description);

    const brand = rng.chance(0.04) ? null : rng.pick(BRANDS);
    const reference = rng.chance(0.45) ? `REF-${String(rng.int(1, 99999)).padStart(5, '0')}` : null;
    const [minCents, maxCents] = spec.cents;
    const skew = rng.next() ** 2;
    const cents = Math.round(minCents + (maxCents - minCents) * skew);
    // 10% of products carry sub-cent precision (unit prices are numeric(18,6) in storage).
    const basePrice = cents * 100 + (rng.chance(0.1) ? rng.int(1, 99) : 0);

    products.push({
      basePrice,
      product: {
        code,
        description,
        active: !rng.chance(0.07),
        usageCode: rng.weighted(USAGE_WEIGHTS),
        groupCode: GROUP_FIRST_CODE + groupIndex,
        unit: rng.pick(spec.units),
        brand,
        reference,
      },
    });
  }
  return { groups, products };
}

// ---- price tables -------------------------------------------------------------------------------

const VERSION_IDS = {
  [DEMO_MAIN_TABLE_CODE]: { older: 501, effective: 502 },
  [DEMO_DERIVED_TABLE_CODE]: { older: 503, effective: 504 },
  [DEMO_FALLBACK_TABLE_CODE]: { older: 505, effective: 506 },
} as const;

const DERIVED_PERCENT = '15';

function isSellable(product: Product): boolean {
  return product.usageCode !== null && DEMO_SELLABLE_USAGE_CODES.includes(product.usageCode);
}

interface PriceSpec {
  readonly versionId: number;
  /** Multiplier applied to the product's base price, in per-mille. */
  readonly perMille: number;
  readonly coverage: { readonly sellable: number; readonly other: number; readonly inactive: number };
  readonly zeroRate: number;
}

function buildPriceRows(rng: Prng, products: readonly ProductBuild[], spec: PriceSpec): ListPrice[] {
  const rows: ListPrice[] = [];
  for (const { product, basePrice } of products) {
    const probability = !product.active
      ? spec.coverage.inactive
      : isSellable(product)
        ? spec.coverage.sellable
        : spec.coverage.other;
    if (!rng.chance(probability)) continue;
    // Explicit zero rows exist in the ERP and are kept distinct from "no row" (F-42).
    const zero = rng.chance(spec.zeroRate);
    const unitPrice = zero ? '0' : fixedToDecimal(Math.round((basePrice * spec.perMille) / 1000), 4);
    rows.push({ versionId: spec.versionId, productCode: product.code, unitPrice });
  }
  return rows;
}

// ---- assembly -----------------------------------------------------------------------------------

function deepFreeze<T>(value: T): T {
  if (typeof value === 'object' && value !== null && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

export function generateDemoDataset(seed: number = DEMO_SEED): DemoDataset {
  const rng = new Prng(seed);
  const { sellers, links } = buildSellers();
  const customers = buildCustomers(rng, sellers);
  const { groups, products } = buildProducts(rng);

  const main = VERSION_IDS[DEMO_MAIN_TABLE_CODE];
  const derived = VERSION_IDS[DEMO_DERIVED_TABLE_CODE];
  const fallback = VERSION_IDS[DEMO_FALLBACK_TABLE_CODE];

  const priceTables: PriceTable[] = [
    { code: DEMO_MAIN_TABLE_CODE, name: 'Tabela Balcão (demonstração)', active: true, originTableCode: null, percent: null },
    { code: DEMO_DERIVED_TABLE_CODE, name: 'Tabela Atacado derivada (demonstração)', active: true, originTableCode: DEMO_MAIN_TABLE_CODE, percent: DERIVED_PERCENT },
    { code: DEMO_FALLBACK_TABLE_CODE, name: 'Tabela Especial (demonstração)', active: true, originTableCode: null, percent: null },
  ];
  const priceTableVersions: PriceTableVersion[] = [
    { versionId: main.older, tableCode: DEMO_MAIN_TABLE_CODE, effectiveFrom: DEMO_OLDER_VERSION_FROM },
    { versionId: main.effective, tableCode: DEMO_MAIN_TABLE_CODE, effectiveFrom: DEMO_EFFECTIVE_VERSION_FROM },
    { versionId: derived.older, tableCode: DEMO_DERIVED_TABLE_CODE, effectiveFrom: DEMO_OLDER_VERSION_FROM },
    { versionId: derived.effective, tableCode: DEMO_DERIVED_TABLE_CODE, effectiveFrom: DEMO_EFFECTIVE_VERSION_FROM },
    { versionId: fallback.older, tableCode: DEMO_FALLBACK_TABLE_CODE, effectiveFrom: DEMO_OLDER_VERSION_FROM },
    { versionId: fallback.effective, tableCode: DEMO_FALLBACK_TABLE_CODE, effectiveFrom: DEMO_FALLBACK_EFFECTIVE_FROM },
  ];

  // A derived table has no rows of its own (F-41): its prices are a percentage on the origin table.
  // The mirror stores versions and rows; the derivation rule is not implemented here (S2.3, NEEDS VALIDATION).
  const listPrices: ListPrice[] = [
    ...buildPriceRows(rng, products, {
      versionId: main.older,
      perMille: 940,
      coverage: { sellable: 0.9, other: 0.25, inactive: 0.3 },
      zeroRate: 0.02,
    }),
    ...buildPriceRows(rng, products, {
      versionId: main.effective,
      perMille: 1000,
      coverage: { sellable: 0.93, other: 0.3, inactive: 0 },
      zeroRate: 0.03,
    }),
    ...buildPriceRows(rng, products, {
      versionId: fallback.older,
      perMille: 1020,
      coverage: { sellable: 0.8, other: 0.15, inactive: 0.2 },
      zeroRate: 0.02,
    }),
    ...buildPriceRows(rng, products, {
      versionId: fallback.effective,
      perMille: 1080,
      coverage: { sellable: 0.85, other: 0.2, inactive: 0 },
      zeroRate: 0.03,
    }),
  ];

  for (const row of listPrices) {
    if (canonicalDecimal(row.unitPrice) !== row.unitPrice) throw new RangeError('non-canonical fixture price');
  }

  return deepFreeze({
    sellers,
    sellerManagerLinks: links,
    customers,
    productGroups: groups,
    products: products.map((p) => p.product),
    priceTables,
    priceTableVersions,
    listPrices,
  });
}

let cached: DemoDataset | undefined;

/** The default demo dataset (seed `DEMO_SEED`), generated once per process. Frozen. */
export function getDemoDataset(): DemoDataset {
  cached ??= generateDemoDataset();
  return cached;
}
