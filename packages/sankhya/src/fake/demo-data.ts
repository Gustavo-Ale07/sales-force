/**
 * SYNTHETIC demo dataset of an industrial distributor, generated deterministically from a seed.
 * Nothing here is real: company and person names are invented, tax ids carry deliberately wrong
 * check digits (and a `9999`/`999` marker), and there is no phone, e-mail or address. Provenance:
 * generated by this module (slice 1, 2026-09-18); no Sankhya capture was used or consulted.
 *
 * The dataset only uses the Sales Force-shaped domain types, so it cannot express ERP-only facts
 * (city/UF, manager code on a seller, per-version percentages).
 */
export interface DemoSellerManagerLink {
  readonly sellerCode: number;
  /** `null` = has no manager (top of the hierarchy). The domain `Seller` has no manager field yet (R35/R36). */
  readonly managerSellerCode: number | null;
}

export interface DemoDataset {
  readonly sellers: readonly Seller[];
  readonly sellerManagerLinks: readonly DemoSellerManagerLink[];
  readonly customers: readonly Customer[];
  readonly productGroups: readonly ProductGroup[];
  readonly products: readonly Product[];
  readonly priceTables: readonly PriceTable[];
  readonly priceTableVersions: readonly PriceTableVersion[];
  readonly listPrices: readonly ListPrice[];
}

