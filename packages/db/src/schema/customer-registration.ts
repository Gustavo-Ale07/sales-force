// Module: customers — a customer created in the Force and delivered to the ERP through integration_outbox (D-AR).
// One row per creation request. The row holds the state the creator sees ("aguardando envio", confirmed, rejected);
// the request payload itself travels in integration_outbox.payload. Personal data here is limited to what the
// creator must see and what the duplicate check needs (name, tax id); it is never logged.
import { sql } from 'drizzle-orm';
import { check, index, integer, pgTable, text, timestamp, uniqueIndex, uuid } from 'drizzle-orm/pg-core';
import { inList } from './_util.js';
import { account } from './iam.js';

export const customerRegistrationStatuses = ['pending', 'confirmed', 'rejected', 'unknown'] as const;
export type CustomerRegistrationStatus = (typeof customerRegistrationStatuses)[number];

export const customerRegistrationRefusalReasons = ['document_already_registered'] as const;

/**
 * A creation attempt refused before anything was recorded (today: the document is already taken). It exists only so the
 * refused attempt counts toward the per-account hourly limit (a refused duplicate must not be a free existence probe
 * for CPF/CNPJ). Deliberately holds no document, no hash of it and no name: account, instant and a reason code.
 */
export const customerRegistrationRefusal = pgTable(
  'customer_registration_refusal',
  {
    /** UUIDv7 generated by the application (DATA-1). */
    id: uuid('id').primaryKey(),
    accountId: uuid('account_id')
      .notNull()
      .references(() => account.id),
    reason: text('reason').notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    check('customer_registration_refusal_reason_chk', sql`${t.reason} in (${inList(customerRegistrationRefusalReasons)})`),
    // Serves: the per-account hourly attempt count (refusals + creations) and the FK lookup on account.
    index('customer_registration_refusal_account_created_idx').on(t.accountId, t.createdAt.desc()),
  ],
);

export const customerRegistration = pgTable(
  'customer_registration',
  {
    /** UUIDv7 generated by the application (DATA-1); also the outbox aggregate id. */
    id: uuid('id').primaryKey(),
    /** Client-generated idempotency key, unique per creating account. */
    clientRequestId: uuid('client_request_id').notNull(),
    /** SHA-256 (hex) of the canonical request: same id with another payload is a conflict. */
    requestHash: text('request_hash').notNull(),
    createdByAccountId: uuid('created_by_account_id')
      .notNull()
      .references(() => account.id),
    /** `force:<clientRequestId>`, the value written to the dedicated ERP origin field (SNK-4/SNK-5). */
    originKey: text('origin_key').notNull(),
    status: text('status').notNull().default('pending'),
    /** Digits only (CPF/CNPJ). */
    taxId: text('tax_id').notNull(),
    name: text('name').notNull(),
    sellerCode: integer('seller_code'),
    /** The real code once the ERP confirmed it; NULL until then. */
    erpCustomerCode: integer('erp_customer_code'),
    /** Stable reason code of a rejection (e.g. duplicate_document), never free text from the ERP. */
    rejectionCode: text('rejection_code'),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp('updated_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    check('customer_registration_status_chk', sql`${t.status} in (${inList(customerRegistrationStatuses)})`),
    check('customer_registration_tax_id_chk', sql`${t.taxId} ~ '^[0-9]{11}$|^[0-9]{14}$'`),
    check(
      'customer_registration_confirmed_chk',
      sql`(${t.status} = 'confirmed') = (${t.erpCustomerCode} is not null)`,
    ),
    // Idempotent creation. Serves: POST replay lookup by (account, client request id); also the FK lookup on account.
    uniqueIndex('customer_registration_account_request_uq').on(t.createdByAccountId, t.clientRequestId),
    // One origin key is delivered at most once.
    uniqueIndex('customer_registration_origin_key_uq').on(t.originKey),
    // Serves: live duplicate check against registrations still in flight (pending or unknown).
    index('customer_registration_tax_id_open_idx')
      .on(t.taxId)
      .where(sql`${t.status} in ('pending', 'unknown')`),
    // Serves: the per-account hourly creation limit and the creator's own list of in-flight customers.
    index('customer_registration_account_created_idx').on(t.createdByAccountId, t.createdAt.desc()),
  ],
);
