import { z } from 'zod';
import { IsoTimestampSchema, UuidSchema, codeInt, named } from './primitives.js';

/**
 * Tarefas (RF-ACT-1..3). Creation and completion are idempotent so the device can replay them from its outbox:
 * the task id is minted on the device and doubles as the request id; completing a completed task answers the same.
 */

export const TaskTypeSchema = z.enum(['call', 'visit', 'email', 'whatsapp', 'meeting', 'other']);
export type TaskTypeValue = z.infer<typeof TaskTypeSchema>;
export const TaskStatusSchema = z.enum(['pending', 'completed', 'cancelled']);
export type TaskStatusValue = z.infer<typeof TaskStatusSchema>;

export const TASK_REMINDER_LEAD_VALUES = [0, 15, 30, 60, 120, 1440] as const;
const ReminderLeadSchema = z
  .number()
  .int()
  .refine((v) => (TASK_REMINDER_LEAD_VALUES as readonly number[]).includes(v), 'Antecedência de lembrete inválida');

export const TaskSchema = named(
  'Task',
  z.object({
    id: UuidSchema,
    type: TaskTypeSchema,
    title: z.string(),
    description: z.string().nullable(),
    dueAt: IsoTimestampSchema,
    reminderLeadMinutes: z.number().int().nullable(),
    customerCode: z.number().int().nullable(),
    /** Name of the linked customer, when it is inside the caller scope. */
    customerName: z.string().nullable(),
    status: TaskStatusSchema,
    completedAt: IsoTimestampSchema.nullable(),
    assigneeAccountId: UuidSchema,
    assigneeName: z.string(),
    version: z.number().int().min(1),
    createdAt: IsoTimestampSchema,
    updatedAt: IsoTimestampSchema,
  }),
);
export type Task = z.infer<typeof TaskSchema>;

export const TasksQuerySchema = z.object({
  /** Absent = every status. */
  status: TaskStatusSchema.optional(),
  customerCode: z.coerce.number().int().min(0).optional(),
  limit: z.coerce.number().int().min(1).max(500).default(200),
});
export type TasksQuery = z.infer<typeof TasksQuerySchema>;

export const TasksResponseSchema = named('TasksResponse', z.object({ items: z.array(TaskSchema) }));
export type TasksResponse = z.infer<typeof TasksResponseSchema>;

export const TaskPathSchema = z.object({ id: UuidSchema });

/** `POST /tasks`. `id` is generated by the client (UUID) and is the idempotency key. */
export const CreateTaskRequestSchema = named(
  'CreateTaskRequest',
  z.strictObject({
    id: UuidSchema,
    type: TaskTypeSchema,
    title: z.string().trim().min(1).max(120),
    description: z.string().max(2000).nullable().default(null),
    dueAt: IsoTimestampSchema,
    reminderLeadMinutes: ReminderLeadSchema.nullable().default(null),
    customerCode: codeInt().nullable().default(null),
  }),
);
export type CreateTaskRequest = z.infer<typeof CreateTaskRequestSchema>;

/** `POST /tasks/{id}/complete`. `completedAt` is the moment the user did it (offline); the server clamps it to now. */
export const CompleteTaskRequestSchema = named(
  'CompleteTaskRequest',
  z.strictObject({ completedAt: IsoTimestampSchema.optional() }),
);
export type CompleteTaskRequest = z.infer<typeof CompleteTaskRequestSchema>;
